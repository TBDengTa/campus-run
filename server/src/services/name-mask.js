/**
 * 姓名脱敏（**唯一实现**）。
 *
 * 为什么抽出来：排行榜与北斗播报都要把「陈宇航」显示成「陈**」。
 * 两处各写一份 `slice(0,1)+'**'` 是最容易漂移的那类复制粘贴 ——
 * 有一天有人改了排行榜的口径（比如改成保留两字），播报这边就会漏改，
 * 于是同一个页面上两种脱敏格式并存，而且没人会发现。
 *
 * 口径（与 routes/ranking.js 原实现逐字一致，改造前后不产生差异）：
 *   张三丰 → 张** ／ 张三 → 张* ？不 —— 统一 张**；
 *   单字名（如「李」）→ 李*；
 *   空名 → 「匿名同学」。
 *
 * ⚠️ 本函数只做**展示**脱敏。调用方必须保证：
 *   ① 完整姓名**永不下发给客户端**（不是「下发了但前端不显示」）；
 *   ② 脱敏后的字符串不可反推（这里只保留首字，符合）。
 */
function maskName(name) {
  const s = String(name == null ? '' : name).trim();
  if (!s) return '匿名同学';
  if (s.length === 1) return s + '*';
  return s.slice(0, 1) + '**';
}

module.exports = { maskName };
